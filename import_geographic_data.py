from main.models import Province, County, District, Dehestan

def clear_all_data():
    """حذف تمام داده‌های موجود"""
    print("🗑️  حذف داده‌های قبلی...")
    Dehestan.objects.all().delete()
    District.objects.all().delete()
    County.objects.all().delete()
    Province.objects.all().delete()
    print("✅ داده‌های قبلی حذف شدند\n")

def import_province_data(province_name, capital, counties_data):
    """
    وارد کردن اطلاعات یک استان
    
    Args:
        province_name: نام استان
        capital: مرکز استان
        counties_data: لیست شهرستان‌ها و اطلاعات آنها
    """
    print(f"{'='*70}")
    print(f"📍 استان: {province_name}")
    print(f"🏛️  مرکز: {capital}")
    print(f"{'='*70}\n")
    
    # ایجاد استان
    province, created = Province.objects.get_or_create(
        name=province_name,
        defaults={'capital': capital}
    )
    
    if created:
        print(f"✅ استان {province_name} ایجاد شد")
    else:
        print(f"ℹ️  استان {province_name} از قبل وجود دارد")
    
    total_counties = 0
    total_districts = 0
    total_dehestans = 0
    
    # پردازش شهرستان‌ها
    for county_name, districts_data in counties_data.items():
        county, created = County.objects.get_or_create(
            province=province,
            name=county_name
        )
        total_counties += 1
        
        if created:
            print(f"  ✅ شهرستان: {county_name}")
        
        # پردازش بخش‌ها
        for district_name, dehestans_list in districts_data.items():
            district, created = District.objects.get_or_create(
                county=county,
                name=district_name
            )
            total_districts += 1
            
            if created:
                print(f"    ✅ بخش: {district_name}")
            
            # پردازش دهستان‌ها
            if dehestans_list and dehestans_list != ['-'] and dehestans_list != ['']:
                for dehestan_name in dehestans_list:
                    if dehestan_name and dehestan_name != '-':
                        dehestan, created = Dehestan.objects.get_or_create(
                            district=district,
                            name=dehestan_name
                        )
                        total_dehestans += 1
                        
                        if created:
                            print(f"      ✅ دهستان: {dehestan_name}")
    
    print(f"\n{'='*70}")
    print(f"📊 آمار استان {province_name}:")
    print(f"   🏘️  شهرستان‌ها: {total_counties}")
    print(f"   📍 بخش‌ها: {total_districts}")
    print(f"   🏡 دهستان‌ها: {total_dehestans}")
    print(f"{'='*70}\n\n")
    
    return province


